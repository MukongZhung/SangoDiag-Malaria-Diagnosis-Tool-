"""Bundle the synthetic Zetaris tables and demo cases into mobile-app/js/data.js.

The phone keeps a read-only copy of the register so it can decide with no network.
Run from the repository root after the CSVs change:

    python mobile-app/scripts/build_data.py
"""
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, "synthetic_data")
OUT = os.path.join(ROOT, "mobile-app", "js", "data.js")


def rows(name):
    with open(os.path.join(DATA, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


with open(os.path.join(ROOT, "examples", "demo_cases.json"), encoding="utf-8") as f:
    cases = json.load(f)

bundle = {
    "patients": rows("patients.csv"),
    "epidemiology": rows("regional_epidemiology.csv"),
    "visits": rows("clinical_visits.csv"),
    "demo_cases": cases,
}

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by mobile-app/scripts/build_data.py from synthetic_data/ and examples/demo_cases.json.\n")
    f.write("// Synthetic demo data only. Do not edit by hand.\n")
    f.write("export const BUNDLE = " + json.dumps(bundle, indent=1, ensure_ascii=False) + ";\n")
print("wrote", OUT)
