// Builds the field app for Vercel into mobile-app/dist with Node only:
//   1. js/data.js from synthetic_data/ and examples/demo_cases.json (same content as build_data.py)
//   2. the PNG icons from the SVGs (sharp)
//   3. a copy of the app files, without scripts, tests and dev files
// Vercel settings live in mobile-app/vercel.json (root directory: mobile-app).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ROOT = path.dirname(APP);
const DIST = path.join(APP, "dist");

// 1. Register data. The CSVs are plain (no quoted fields), like csv.DictReader reads them.
function rows(name) {
  const lines = fs.readFileSync(path.join(ROOT, "synthetic_data", name), "utf8").split(/\r?\n/).filter((l) => l.trim());
  const head = lines[0].split(",");
  return lines.slice(1).map((l) => { const v = l.split(","); return Object.fromEntries(head.map((h, i) => [h, v[i] === undefined ? "" : v[i]])); });
}
const bundle = {
  patients: rows("patients.csv"),
  epidemiology: rows("regional_epidemiology.csv"),
  visits: rows("clinical_visits.csv"),
  demo_cases: JSON.parse(fs.readFileSync(path.join(ROOT, "examples", "demo_cases.json"), "utf8")),
};
fs.writeFileSync(path.join(APP, "js", "data.js"),
  "// Generated by mobile-app/scripts/vercel-build.mjs from synthetic_data/ and examples/demo_cases.json.\n" +
  "// Synthetic demo data only. Do not edit by hand.\n" +
  "export const BUNDLE = " + JSON.stringify(bundle, null, 1) + ";\n");
console.log("data.js:", bundle.patients.length, "patients,", bundle.epidemiology.length, "villages,", bundle.visits.length, "visits");

// 2. Icons (Android needs PNG icons to install the app).
const icons = [["logo.svg", "icon-192.png", 192], ["logo.svg", "icon-512.png", 512], ["maskable.svg", "maskable-512.png", 512]];
try {
  const sharp = (await import("sharp")).default;
  for (const [src, out, size] of icons) {
    await sharp(path.join(APP, "icons", src), { density: 72 * size / 120 * 2 }).resize(size, size).png().toFile(path.join(APP, "icons", out));
  }
  console.log("icons: built");
} catch (e) {
  console.warn("icons: not built (" + e.message + "). The app works, but Android may not offer to install it.");
}

// 3. Copy the app.
const SKIP = new Set(["dist", "node_modules", "scripts", "tests", "android", "package.json", "package-lock.json", "README.md", "vercel.json", ".vercel"]);
fs.rmSync(DIST, { recursive: true, force: true });
function copy(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (from === APP && SKIP.has(e.name)) continue;
    if (e.name.startsWith(".")) continue;
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) copy(a, b); else fs.copyFileSync(a, b);
  }
}
copy(APP, DIST);
console.log("dist:", fs.readdirSync(DIST).join(" "));
