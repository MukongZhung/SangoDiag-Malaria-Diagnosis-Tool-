export function pack(lang) {
  return L[lang] || L.en;
}

export function ui(lang, key, ...args) {
  const p = pack(lang).ui[key], e = L.en.ui[key];
  const v = p !== null && p !== undefined ? p : e !== null && e !== undefined ? e : key;
  return typeof v === "function" ? v(...args) : v;
}

export function renderReason(lang, r) {
  const x = pack(lang);
  return x.reasons[r.key](r.params, x);
}

export function renderStep(lang, s) {
  const x = pack(lang);
  return x.steps[s.key](s.params || {}, x);
}
